import { open, readFile, rm, stat } from 'node:fs/promises'
import { resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

/**
 * Builds the SQL that makes a restored database forget the accounts that were deleted after the
 * copy it came from. A restore (D1 Time Travel or a backup) brings those accounts back; this
 * deletes them again before anyone can sign in.
 *
 * Input: the live `account_tombstones` rows, exported BEFORE the restore, because a restore also
 * rewinds that table. Either a plain JSON array of { user_id, deleted_at } or the output of
 * `wrangler d1 execute <db> --remote --json --command "SELECT user_id, deleted_at FROM account_tombstones"`.
 * Run it on a database whose migrations are applied (the table must exist). See scripts/ops/restore.md.
 *
 * The SQL is idempotent. Account ids are validated as UUIDs and numbers as integers before they
 * reach the SQL text, so a damaged or hostile input file cannot inject statements.
 */
const USER_ID = /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i
const ROWS_PER_INSERT = 50

/** The rows of a tombstone export, validated. */
export function parseTombstones(text) {
  let parsed
  try {
    parsed = JSON.parse(text)
  } catch {
    throw new Error('The tombstone export is not JSON.')
  }
  // wrangler --json wraps each statement's rows as [{ results: [...] }].
  const rows = Array.isArray(parsed)
    ? parsed.flatMap((entry) => (entry && Array.isArray(entry.results) ? entry.results : [entry]))
    : null
  if (!rows) throw new Error('The tombstone export is not a list of rows.')
  const seen = new Map()
  for (const row of rows) {
    const userId = row?.user_id
    const deletedAt = row?.deleted_at
    if (typeof userId !== 'string' || !USER_ID.test(userId)) {
      throw new Error('The tombstone export has a row with an invalid user_id.')
    }
    if (!Number.isSafeInteger(deletedAt) || deletedAt < 0) {
      throw new Error('The tombstone export has a row with an invalid deleted_at.')
    }
    seen.set(userId.toLowerCase(), deletedAt)
  }
  return [...seen].map(([userId, deletedAt]) => ({ userId, deletedAt }))
}

/**
 * The reconciliation SQL. Order matters: tombstones first (the export's rows, plus every account
 * the restored copy shows mid-deletion), then the deletes that read the table, then sessions.
 * Deleting a user cascades to every table that references it.
 */
export function reconcileSql(tombstones) {
  const statements = [
    '-- Generated by scripts/ops/reconcile-restore.mjs. Idempotent.',
    // An account that was mid-deletion in the copy has its deletion finished, not undone.
    'INSERT OR IGNORE INTO account_tombstones (user_id, deleted_at) SELECT id, deleting_at FROM users WHERE deleting_at IS NOT NULL;',
  ]
  for (let at = 0; at < tombstones.length; at += ROWS_PER_INSERT) {
    const values = tombstones
      .slice(at, at + ROWS_PER_INSERT)
      .map(({ userId, deletedAt }) => `('${userId}', ${deletedAt})`)
      .join(', ')
    statements.push(
      `INSERT OR IGNORE INTO account_tombstones (user_id, deleted_at) VALUES ${values};`,
    )
  }
  statements.push(
    'DELETE FROM users WHERE id IN (SELECT user_id FROM account_tombstones);',
    // Sessions in a restored copy may be revoked, or belong to people who signed out since.
    'DELETE FROM sessions;',
  )
  return `${statements.join('\n')}\n`
}

export async function reconcileFile(inputPath, outputPath) {
  const tombstones = parseTombstones(await readFile(resolve(inputPath), 'utf8'))
  const output = resolve(outputPath)
  let handle
  try {
    handle = await open(output, 'wx', 0o600)
  } catch (error) {
    if (error.code === 'EEXIST') {
      throw new Error('Output file already exists; refusing to overwrite it.', { cause: error })
    }
    throw error
  }
  try {
    await handle.writeFile(reconcileSql(tombstones), 'utf8')
    await handle.sync()
  } finally {
    await handle.close()
  }
  if (((await stat(output)).mode & 0o777) !== 0o600) {
    await rm(output, { force: true })
    throw new Error('Could not create private output (expected file mode 0600).')
  }
  return { output, tombstones: tombstones.length }
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const [, , inputPath, outputPath] = process.argv
  if (!inputPath || !outputPath || process.argv.length !== 4) {
    console.error(
      'Usage: node scripts/ops/reconcile-restore.mjs <tombstones.json> <new-output.sql>',
    )
    process.exitCode = 2
  } else {
    try {
      const result = await reconcileFile(inputPath, outputPath)
      console.log(`Wrote ${result.output} for ${result.tombstones} tombstone rows.`)
    } catch (error) {
      console.error(`Could not prepare the reconciliation: ${error.message}`)
      process.exitCode = 1
    }
  }
}
